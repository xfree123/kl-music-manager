"""Tạo static/icons/sprite.svg từ bộ icon Lucide (ISC, https://lucide.dev).

Chạy lại khi cần thêm icon: thêm tên vào ICONS rồi `python packaging/make_icon_sprite.py`.
Tải SVG của gói npm `lucide-static` (phiên bản cố định) qua jsDelivr, gộp thành các <symbol>
dùng bằng `<svg class="icon"><use href="icons/sprite.svg#play"></use></svg>`.
Màu theo CSS (`stroke="currentColor"`).
"""

from __future__ import annotations

import re
import sys
import urllib.request
from pathlib import Path
from typing import List

LUCIDE_VERSION = "1.81.0"
BASE = f"https://cdn.jsdelivr.net/npm/lucide-static@{LUCIDE_VERSION}"
ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "static" / "icons"

ICONS: List[str] = [
    # player
    "skip-back",
    "play",
    "pause",
    "skip-forward",
    "shuffle",
    "repeat",
    "volume",
    "volume-1",
    "volume-2",
    "volume-x",
    # toolbar / menu
    "import",
    "download",
    "trash-2",
    "search",
    "chevron-down",
    "shield-check",
    "refresh-cw",
    "folder-open",
    "folder",
    "list-music",
    "library",
    "settings",
    "circle-help",
    "info",
    "upload",
    # library sidebar
    "smartphone",
    "music",
    "podcast",
    "clapperboard",
    "image",
    # context menu
    "list-start",
    "list-plus",
    "pencil",
    "image-plus",
    "image-off",
    "folder-plus",
    "tags",
    "x",
    "wrench",
    "database",
    "hard-drive",
    "rotate-cw",
    "eraser",
]

ALLOWED_TAGS = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}


def fetch(url: str) -> str:
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read().decode("utf-8")


def to_symbol(name: str, svg: str) -> str:
    """Lấy phần thân của SVG Lucide, chỉ giữ các phần tử hình học (không script/link)."""
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not body:
        raise ValueError(f"{name}: không phải SVG")
    inner = re.sub(r"<!--.*?-->", "", body.group(1), flags=re.S).strip()
    tags = set(re.findall(r"<\s*([a-zA-Z]+)", inner))
    if not tags <= ALLOWED_TAGS:
        raise ValueError(f"{name}: phần tử không cho phép {sorted(tags - ALLOWED_TAGS)}")
    inner = re.sub(r"\s*\n\s*", "", inner)
    return (
        f'  <symbol id="{name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{inner}</symbol>'
    )


def build(names: List[str]) -> str:
    symbols = [to_symbol(n, fetch(f"{BASE}/icons/{n}.svg")) for n in names]
    header = (
        f"<!-- Lucide icons v{LUCIDE_VERSION} (https://lucide.dev), ISC License: "
        "see LICENSE-lucide.txt. Generated by packaging/make_icon_sprite.py -->"
    )
    return "\n".join(
        [header, '<svg xmlns="http://www.w3.org/2000/svg">'] + symbols + ["</svg>", ""]
    )


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "sprite.svg").write_text(build(ICONS), encoding="utf-8")
    (OUT_DIR / "LICENSE-lucide.txt").write_text(fetch(f"{BASE}/LICENSE"), encoding="utf-8")
    print(f"sprite.svg: {len(ICONS)} icon (lucide-static {LUCIDE_VERSION})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
